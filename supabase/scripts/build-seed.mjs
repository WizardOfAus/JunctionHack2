// Make supabase/seed.sql from the committed demo data in app/data.
//
//   node supabase/scripts/build-seed.mjs [--out <file>]
//
// The seed replaces all rows in the Koti demo tables in one transaction, so
// you can run it again after app/data changes. It copies values; it does not
// calculate or change them.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const here = dirname(new URL(import.meta.url).pathname);
const dataDir = resolve(here, '../../app/data');
const { values: args } = parseArgs({ options: { out: { type: 'string', default: resolve(here, '../seed.sql') } } });

// Blank CSV headers get a name. A blank first column holds the row label.
const BLANK_HEADERS = { benchmarks_by_age: { 1: 'quantile' } };

const sql = (value) => {
	if (value === null || value === undefined) return 'null';
	if (typeof value === 'number') {
		if (!Number.isFinite(value)) throw new Error(`Not a finite number: ${value}`);
		return String(value);
	}
	if (typeof value === 'boolean') return value ? 'true' : 'false';
	if (typeof value === 'object') return `${sql(JSON.stringify(value))}::jsonb`;
	return `'${String(value).replaceAll("'", "''")}'`;
};
const textArray = (items) => `array[${items.map(sql).join(', ')}]::text[]`;

function parseCsv(text) {
	const rows = [];
	let row = [], field = '', quoted = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (quoted) {
			if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
			else if (c === '"') quoted = false;
			else field += c;
		} else if (c === '"') quoted = true;
		else if (c === ',') { row.push(field); field = ''; }
		else if (c === '\n' || c === '\r') {
			if (c === '\r' && text[i + 1] === '\n') i++;
			row.push(field); rows.push(row); row = []; field = '';
		} else field += c;
	}
	if (field !== '' || row.length) { row.push(field); rows.push(row); }
	return rows.filter((r) => !(r.length === 1 && r[0] === ''));
}

const cell = (text) => (text === '' ? null : /^-?\d+(\.\d+)?$/.test(text) ? Number(text) : text);

const lines = ['-- Generated by supabase/scripts/build-seed.mjs from app/data. Do not edit.', 'begin;', ''];
lines.push('delete from public.insight_rows;', 'delete from public.insight_datasets;', 'delete from public.transactions;', 'delete from public.personas;', 'delete from public.demo_clocks;', '');

const clock = JSON.parse(readFileSync(join(dataDir, 'demo-clock.json'), 'utf8'));
for (const [name, c] of Object.entries(clock.clocks)) {
	lines.push(`insert into public.demo_clocks (name, demo_date, history_through, data_start) values (${[name, c.demoDate, c.historyThrough, clock.dataStart].map(sql).join(', ')});`);
}
lines.push('');

const persona = JSON.parse(readFileSync(join(dataDir, 'persona.json'), 'utf8'));
lines.push(`insert into public.personas (customer_id, account_id, as_of, source_revision, provenance, statistics, synthetic) values (${[
	persona.customerId, persona.accountId, persona.asOf, persona.sourceRevision, persona.provenance, persona.statistics, persona.provenance?.synthetic !== false,
].map(sql).join(', ')});`, '');

const txColumns = ['id', 'source_row', 'customer_id', 'bank_account_id', 'tx_date', 'tx_timestamp', 'category', 'tx_amount_eur', 'balance_after_eur', 'transaction_type', 'merchant_id', 'mcc_code', 'amount_cents', 'balance_cents'];
const txValues = persona.transactions.map((t) => {
	if (t.customer_id !== persona.customerId) throw new Error(`Transaction ${t.id} belongs to ${t.customer_id}, not ${persona.customerId}.`);
	if (!Number.isInteger(t.amountCents) || !Number.isInteger(t.balanceCents)) throw new Error(`Transaction ${t.id} has non-integer cents.`);
	return `(${[t.id, t.sourceRow, t.customer_id, t.bank_account_id, t.tx_date, t.tx_timestamp, t.category, t.tx_amount_eur, t.balance_after_eur, t.transaction_type, t.merchant_id || null, t.mcc_code || null, t.amountCents, t.balanceCents].map(sql).join(', ')})`;
});
for (let i = 0; i < txValues.length; i += 200) {
	lines.push(`insert into public.transactions (${txColumns.join(', ')}) values\n${txValues.slice(i, i + 200).join(',\n')};`);
}
lines.push('');

const insightsDir = join(dataDir, 'insights');
const insightCounts = {};
for (const file of readdirSync(insightsDir).filter((f) => f.endsWith('.csv')).sort()) {
	const name = basename(file, '.csv');
	const [header, ...rows] = parseCsv(readFileSync(join(insightsDir, file), 'utf8'));
	const columns = header.map((h, i) => {
		if (h !== '') return h;
		const named = BLANK_HEADERS[name]?.[i] ?? (i === 0 ? 'metric' : undefined);
		if (!named) throw new Error(`${file}: column ${i + 1} has no header and no name in BLANK_HEADERS.`);
		return named;
	});
	if (new Set(columns).size !== columns.length) throw new Error(`${file}: duplicate column names.`);
	lines.push(`insert into public.insight_datasets (name, source_file, columns) values (${sql(name)}, ${sql(`app/data/insights/${file}`)}, ${textArray(columns)});`);
	const values = rows.map((r, index) => {
		if (r.length !== columns.length) throw new Error(`${file}: row ${index + 2} has ${r.length} cells, expected ${columns.length}.`);
		return `(${sql(name)}, ${index}, ${sql(Object.fromEntries(columns.map((c, i) => [c, cell(r[i])])))})`;
	});
	if (values.length) lines.push(`insert into public.insight_rows (dataset, row_index, data) values\n${values.join(',\n')};`);
	insightCounts[name] = values.length;
}

lines.push('', 'commit;', '');
writeFileSync(args.out, lines.join('\n'));
console.log(JSON.stringify({ out: args.out, clocks: Object.keys(clock.clocks).length, personas: 1, transactions: txValues.length, insights: insightCounts }, null, 2));
