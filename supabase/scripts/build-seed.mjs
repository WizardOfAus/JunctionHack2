// Make supabase/seed.sql from the committed demo data in app/data
// (demo clock, persona, insights/*.csv and overlays/*.csv).
//
//   node supabase/scripts/build-seed.mjs [--out <file>]
//
// The seed replaces all rows in the Koti demo tables in one transaction, so
// you can run it again after app/data changes. It copies values; it does not
// calculate or change them.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { basename, dirname, join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

const here = dirname(new URL(import.meta.url).pathname);
const dataDir = resolve(here, '../../app/data');
const { values: args } = parseArgs({ options: { out: { type: 'string', default: resolve(here, '../seed.sql') } } });

// Blank CSV headers get a name. A blank first column holds the row label.
const BLANK_HEADERS = { benchmarks_by_age: { 1: 'quantile' } };

const sql = (value) => {
	if (value === null || value === undefined) return 'null';
	if (typeof value === 'number') {
		if (!Number.isFinite(value)) throw new Error(`Not a finite number: ${value}`);
		return String(value);
	}
	if (typeof value === 'boolean') return value ? 'true' : 'false';
	if (typeof value === 'object') return `${sql(JSON.stringify(value))}::jsonb`;
	return `'${String(value).replaceAll("'", "''")}'`;
};
const textArray = (items) => `array[${items.map(sql).join(', ')}]::text[]`;

function parseCsv(text) {
	const rows = [];
	let row = [], field = '', quoted = false;
	for (let i = 0; i < text.length; i++) {
		const c = text[i];
		if (quoted) {
			if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
			else if (c === '"') quoted = false;
			else field += c;
		} else if (c === '"') quoted = true;
		else if (c === ',') { row.push(field); field = ''; }
		else if (c === '\n' || c === '\r') {
			if (c === '\r' && text[i + 1] === '\n') i++;
			row.push(field); rows.push(row); row = []; field = '';
		} else field += c;
	}
	if (field !== '' || row.length) { row.push(field); rows.push(row); }
	return rows.filter((r) => !(r.length === 1 && r[0] === ''));
}

// Codes and IDs stay text, and so do values with a leading zero (postal codes such as 00100).
const TEXT_COLUMN = /(^|_)(code|id)$/;
const cell = (column, text) => {
	if (text === '') return null;
	if (TEXT_COLUMN.test(column) || !/^-?(0|[1-9]\d*)(\.\d+)?$/.test(text)) return text;
	return Number(text);
};

const lines = ['-- Generated by supabase/scripts/build-seed.mjs from app/data. Do not edit.', 'begin;', ''];
lines.push('delete from public.csv_rows;', 'delete from public.csv_datasets;', 'delete from public.transactions;', 'delete from public.personas;', 'delete from public.demo_clocks;', '');

const clock = JSON.parse(readFileSync(join(dataDir, 'demo-clock.json'), 'utf8'));
for (const [name, c] of Object.entries(clock.clocks)) {
	lines.push(`insert into public.demo_clocks (name, demo_date, history_through, data_start) values (${[name, c.demoDate, c.historyThrough, clock.dataStart].map(sql).join(', ')});`);
}
lines.push('');

const catalogue=JSON.parse(readFileSync(join(dataDir,'personas/catalogue.json'),'utf8'));
const records=JSON.parse(readFileSync(join(dataDir,'personas/records.json'),'utf8')).personas;
const txColumns = ['id', 'source_row', 'customer_id', 'bank_account_id', 'tx_date', 'tx_timestamp', 'category', 'tx_amount_eur', 'balance_after_eur', 'transaction_type', 'merchant_id', 'mcc_code', 'amount_cents', 'balance_cents'];
const txValues=[];
const seen=new Set();
for(const entry of catalogue.personas){
 const persona=JSON.parse(readFileSync(join(dataDir,entry.id===catalogue.defaultId?'persona.json':`personas/${entry.id}.json`),'utf8'));
 const record=records[entry.id];
 if(persona.customerId!==entry.customerId||record.customerId!==entry.customerId||record.rowCount!==persona.transactions.length)throw new Error(`Invalid catalogue metadata for ${entry.id}.`);
 const provenance={...(persona.provenance??{}),synthetic:true,personaId:entry.id,catalogue:entry,record};
 lines.push(`insert into public.personas (customer_id, account_id, as_of, source_revision, provenance, statistics, synthetic) values (${[entry.customerId,record.accountId,clock.clocks.current.demoDate,persona.sourceRevision,provenance,persona.statistics??{},true].map(sql).join(', ')});`, '');
 for(const t of persona.transactions){
  if(t.customer_id!==entry.customerId||t.bank_account_id!==record.accountId||t.tx_date>clock.clocks.current.historyThrough)throw new Error(`Wrong customer, account or history date in ${entry.id}.`);
  if(seen.has(t.id)||!Number.isSafeInteger(t.amountCents)||!Number.isSafeInteger(t.balanceCents))throw new Error(`Duplicate row or invalid cents in ${entry.id}.`);
  seen.add(t.id);
  txValues.push(`(${[t.id,t.sourceRow,t.customer_id,t.bank_account_id,t.tx_date,t.tx_timestamp,t.category,t.tx_amount_eur,t.balance_after_eur,t.transaction_type,t.merchant_id||null,t.mcc_code||null,t.amountCents,t.balanceCents].map(sql).join(', ')})`);
 }
}
for(let i=0;i<txValues.length;i+=200)lines.push(`insert into public.transactions (${txColumns.join(', ')}) values\n${txValues.slice(i,i+200).join(',\n')};`);
lines.push('');

const csvCounts = {};
for (const folder of ['insights', 'overlays']) {
	const dir = join(dataDir, folder);
	for (const file of readdirSync(dir).filter((f) => f.endsWith('.csv')).sort()) {
		const name = basename(file, '.csv');
		if (name in csvCounts) throw new Error(`${folder}/${file}: dataset name ${name} is already used.`);
		const [header, ...rows] = parseCsv(readFileSync(join(dir, file), 'utf8'));
		const columns = header.map((h, i) => {
			if (h !== '') return h;
			const named = BLANK_HEADERS[name]?.[i] ?? (i === 0 ? 'metric' : undefined);
			if (!named) throw new Error(`${file}: column ${i + 1} has no header and no name in BLANK_HEADERS.`);
			return named;
		});
		if (new Set(columns).size !== columns.length) throw new Error(`${file}: duplicate column names.`);
		lines.push(`insert into public.csv_datasets (name, folder, source_file, columns) values (${sql(name)}, ${sql(folder)}, ${sql(`app/data/${folder}/${file}`)}, ${textArray(columns)});`);
		const values = rows.map((r, index) => {
			if (r.length !== columns.length) throw new Error(`${file}: row ${index + 2} has ${r.length} cells, expected ${columns.length}.`);
			return `(${sql(name)}, ${index}, ${sql(Object.fromEntries(columns.map((c, i) => [c, cell(c, r[i])])))})`;
		});
		for (let i = 0; i < values.length; i += 200) {
			lines.push(`insert into public.csv_rows (dataset, row_index, data) values\n${values.slice(i, i + 200).join(',\n')};`);
		}
		csvCounts[name] = values.length;
	}
}

lines.push('', 'commit;', '');
writeFileSync(args.out, lines.join('\n'));
console.log(JSON.stringify({ out: args.out, clocks: Object.keys(clock.clocks).length, personas: catalogue.personas.length, transactions: txValues.length, csv: csvCounts }, null, 2));
